let currentLanguage = localStorage.getItem('language') || 'fr';

function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    updatePageContent();
    document.documentElement.lang = lang;
}

function getTranslation(key) {
    return translations[currentLanguage][key] || key;
}

function updatePageContent() {
    // Navigation
    document.querySelectorAll('a.nav-link').forEach((link, index) => {
        const navKeys = ['navHome', 'navAbout', 'navSkills', 'navEducation', 'navProjects', 'navContact'];
        if (navKeys[index]) {
            link.textContent = getTranslation(navKeys[index]);
        }
    });

    // Hero section
    const heroTitle = document.querySelector('.hero-title .neon-glow');
    if (heroTitle) heroTitle.textContent = getTranslation('heroTitle');

    // Ensure there's a single `.hero-description` element (avoid accidental duplicates)
    const heroDescs = document.querySelectorAll('.hero-description');
    if (heroDescs.length > 1) {
        heroDescs.forEach((el, i) => {
            if (i > 0) el.remove();
        });
    }
    const heroDesc = document.querySelector('.hero-description');
    if (heroDesc) {
        // Replace content fully to avoid text accumulation / overlap
        heroDesc.textContent = '';
        heroDesc.textContent = getTranslation('heroDescription');
    }

    // Hero buttons
    const heroButtons = document.querySelectorAll('.hero-buttons .btn');
    if (heroButtons.length >= 1) {
        const primaryBtn = heroButtons[0];
        primaryBtn.innerHTML = `<span>${getTranslation('heroBtnProjects')}</span><i class="fas fa-arrow-right"></i>`;
    }
    if (heroButtons.length >= 2) {
        const secondaryBtn = heroButtons[1];
        secondaryBtn.innerHTML = `<i class="fas fa-download"></i><span>${getTranslation('heroBtnCV')}</span>`;
    }

    // About section
    const aboutTitle = document.querySelector('#about .section-title');
    if (aboutTitle) {
        aboutTitle.innerHTML = `<span class="highlight">${currentLanguage === 'fr' ? 'À propos' : 'About'}</span> ${currentLanguage === 'fr' ? 'de moi' : 'me'}`;
    }

    const aboutText = document.querySelector('.about-text p');
    if (aboutText) aboutText.textContent = getTranslation('aboutText');

    // About tech icons
    const techIcons = document.querySelectorAll('.tech-icon-item p');
    const techKeys = ['aboutTechElectronics', 'aboutTechProgramming', 'aboutTechRobotics', 'aboutTechAI'];
    techIcons.forEach((icon, index) => {
        if (techKeys[index]) icon.textContent = getTranslation(techKeys[index]);
    });

    // Skills section
    const skillsTitle = document.querySelector('#skills .section-title');
    if (skillsTitle) {
        skillsTitle.innerHTML = `<span class="highlight">${currentLanguage === 'fr' ? 'Mes' : 'My'}</span> ${getTranslation('skillsTitle')}`;
    }

    // Skills categories headers
    const categoryHeaders = document.querySelectorAll('.category-header h3');
    const categoryKeys = ['skillsCategoryProgramming', 'skillsCategoryEmbedded', 'skillsCategoryControl'];
    categoryHeaders.forEach((header, index) => {
        if (categoryKeys[index]) header.textContent = getTranslation(categoryKeys[index]);
    });

    // Skills items
    const skillItems = document.querySelectorAll('.skill-item');
    const skillsMap = [
        { h4: 'skillCpp', p: 'skillCppDesc' },
        { h4: 'skillPython', p: 'skillPythonDesc' },
        { h4: 'skillOpenCV', p: 'skillOpenCVDesc' },
        { h4: 'skillArduino', p: 'skillArduinoDesc' },
        { h4: 'skillRaspberry', p: 'skillRaspberryDesc' },
        { h4: 'skillElectronics', p: 'skillElectronicsDesc' },
        { h4: 'skillMatlab', p: 'skillMatlabDesc' },
        { h4: 'skillControl', p: 'skillControlDesc' }
    ];

    skillItems.forEach((item, index) => {
        if (skillsMap[index]) {
            const h4 = item.querySelector('h4');
            const p = item.querySelector('p');
            if (h4) h4.textContent = getTranslation(skillsMap[index].h4);
            if (p) p.textContent = getTranslation(skillsMap[index].p);
        }
    });

    // Education section
    const educTitle = document.querySelector('#education .section-title');
    if (educTitle) {
        educTitle.innerHTML = `<span class="highlight">${currentLanguage === 'fr' ? 'Mon' : 'My'}</span> ${getTranslation('educationTitle')}`;
    }

    // Timeline items
    const timelineItems = document.querySelectorAll('.timeline-item');
    if (timelineItems.length >= 3) {
        // Year 1
        const item1h3 = timelineItems[0].querySelector('h3');
        const item1h4 = timelineItems[0].querySelector('h4');
        const item1date = timelineItems[0].querySelector('.timeline-date');
        if (item1h3) item1h3.textContent = getTranslation('educYear1');
        if (item1h4) item1h4.textContent = getTranslation('educUniversity');
        if (item1date) item1date.textContent = getTranslation('educOngoing');

        // Prep
        const item2h3 = timelineItems[1].querySelector('h3');
        const item2h4 = timelineItems[1].querySelector('h4');
        const item2date = timelineItems[1].querySelector('.timeline-date');
        if (item2h3) item2h3.textContent = getTranslation('educPrep');
        if (item2h4) item2h4.textContent = getTranslation('educUniversity');
        if (item2date) item2date.textContent = getTranslation('educPrepDates');

        // Baccalaureate
        const item3h3 = timelineItems[2].querySelector('h3');
        const item3h4 = timelineItems[2].querySelector('h4');
        const item3date = timelineItems[2].querySelector('.timeline-date');
        if (item3h3) item3h3.textContent = getTranslation('educBac');
        if (item3h4) item3h4.textContent = getTranslation('educBacSchool');
        if (item3date) item3date.textContent = getTranslation('educBacDates');
    }

    // Projects section
    const projectsTitle = document.querySelector('#projects .section-title');
    if (projectsTitle) {
        projectsTitle.innerHTML = `<span class="highlight">${currentLanguage === 'fr' ? 'Mes' : 'My'}</span> ${getTranslation('projectsTitle')}`;
    }

    // Project cards
    const projectCards = document.querySelectorAll('.project-showcase-card');
    const projectsMap = [
        { h3: 'project1Title', tech: 'project1Tech', details: ['project1Details1', 'project1Details2', 'project1Details3'] },
        { h3: 'project2Title', tech: 'project2Tech', details: ['project2Details1', 'project2Details2', 'project2Details3'] },
        { h3: 'project3Title', tech: 'project3Tech', details: ['project3Details1', 'project3Details2', 'project3Details3'] },
        { h3: 'project4Title', tech: 'project4Tech', details: ['project4Details1', 'project4Details2'] }
    ];

    projectCards.forEach((card, index) => {
        if (projectsMap[index]) {
            const h3 = card.querySelector('.project-info h3');
            const techList = card.querySelector('.tech-list');
            const detailsList = card.querySelectorAll('.project-details ul li');

            if (h3) h3.textContent = getTranslation(projectsMap[index].h3);
            if (techList) techList.textContent = getTranslation(projectsMap[index].tech);

            detailsList.forEach((detail, detailIndex) => {
                if (projectsMap[index].details[detailIndex]) {
                    detail.textContent = getTranslation(projectsMap[index].details[detailIndex]);
                }
            });
        }
    });

    // Tech used label
    document.querySelectorAll('.tech-used').forEach(el => {
        el.textContent = getTranslation('projectTechUsed');
    });

    // Demo buttons
    document.querySelectorAll('.cta-link').forEach(link => {
        link.innerHTML = `<i class="fas fa-video"></i> ${getTranslation('projectDemo')}`;
    });

    // Contact section
    const contactTitle = document.querySelector('#contact .section-title');
    if (contactTitle) {
        contactTitle.innerHTML = `<span class="highlight">${currentLanguage === 'fr' ? 'Me' : 'Contact'}</span> ${getTranslation('contactTitle')}`;
    }

    // Contact info
    const contactH3 = document.querySelector('.contact-info h3');
    if (contactH3) contactH3.textContent = getTranslation('contactSubtitle');

    const contactP = document.querySelector('.contact-info > p');
    if (contactP) contactP.textContent = getTranslation('contactDescription');

    // Contact items labels
    const contactItems = document.querySelectorAll('.contact-item');
    const contactLabels = ['contactEmail', 'contactLinkedIn', 'contactYouTube'];
    contactItems.forEach((item, index) => {
        if (contactLabels[index]) {
            const h4 = item.querySelector('h4');
            if (h4) h4.textContent = getTranslation(contactLabels[index]);
        }
    });

    // Contact buttons
    const contactBtns = document.querySelectorAll('.contact-btn');
    if (contactBtns.length >= 2) {
        contactBtns[0].innerHTML = `<i class="fas fa-envelope"></i><span>${getTranslation('contactBtnEmail')}</span>`;
        contactBtns[1].innerHTML = `<i class="fab fa-linkedin"></i><span>${getTranslation('contactBtnLinkedIn')}</span>`;
    }

    // Re-initialize typing effect
    initTypingEffect();
}
